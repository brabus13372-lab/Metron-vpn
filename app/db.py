    async def get_balance_transactions(
        self,
        user_id: int,
        limit: int = 50,
    ) -> List[Dict[str, Any]]:
        async with self.connection() as conn:
            rows = await conn.fetch(
                """
                SELECT
                    id,
                    user_id,
                    kind,
                    amount_cents,
                    balance_before,
                    balance_after,
                    reference_type,
                    reference_id,
                    idempotency_key,
                    created_at
                FROM balance_transactions
                WHERE user_id = $1
                ORDER BY created_at DESC, id DESC
                LIMIT $2
                """,
                user_id,
                limit,
            )

            return [
                {
                    **dict(r),
                    "amount": self._cents_to_rubles(r["amount_cents"]),
                    "balance_before_rub": self._cents_to_rubles(r["balance_before"]),
                    "balance_after_rub": self._cents_to_rubles(r["balance_after"]),
                }
                for r in rows
            ]


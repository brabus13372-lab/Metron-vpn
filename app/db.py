"""
Асинхронный слой доступа к PostgreSQL для Metron VPN-бота.

Модель:
- 1 user -> many devices
- paid-доступ живёт через balance и daily billing
- trial использует expire_at
- платежи идемпотентны
- деньги храним как int (копейки), наружу отдаём Decimal
"""

from __future__ import annotations

import logging
import os
from contextlib import asynccontextmanager
from datetime import date, datetime
from decimal import Decimal
from typing import Any, AsyncIterator, Dict, List, Optional

import asyncpg

logger = logging.getLogger(__name__)

USER_STATUSES = ("NEW", "TRIAL", "ACTIVE", "INACTIVE", "EXPIRED")


class Database:
    """Асинхронный доступ к PostgreSQL."""

    def __init__(self, dsn: str, min_size: int = 2, max_size: int = 10):
        self._dsn = dsn
        self._pool: Optional[asyncpg.Pool] = None
        self._min_size = min_size
        self._max_size = max_size

    async def connect(self) -> None:
        self._pool = await asyncpg.create_pool(
            dsn=self._dsn,
            min_size=self._min_size,
            max_size=self._max_size,
            command_timeout=10.0,
        )
        logger.info("DB pool created (min=%s, max=%s)", self._min_size, self._max_size)

    async def disconnect(self) -> None:
        if self._pool:
            await self._pool.close()
            logger.info("DB pool closed")

    @asynccontextmanager
    async def connection(self) -> AsyncIterator[asyncpg.Connection]:
        if not self._pool:
            raise RuntimeError("Pool not initialized")
        async with self._pool.acquire() as conn:
            yield conn

    @asynccontextmanager
    async def transaction(self) -> AsyncIterator[asyncpg.Connection]:
        if not self._pool:
            raise RuntimeError("Pool not initialized")
        async with self._pool.acquire() as conn:
            async with conn.transaction():
                yield conn

    async def init_schema(self) -> None:
        status_list = ", ".join(f"'{s}'" for s in USER_STATUSES)

        create_users = f"""
            CREATE TABLE IF NOT EXISTS users (
                user_id BIGINT PRIMARY KEY,
                username TEXT,
                expire_at TIMESTAMPTZ,
                vless_link TEXT,
                uuid TEXT UNIQUE,
                status TEXT NOT NULL DEFAULT 'NEW'
                    CHECK (status IN ({status_list})),
                notified BOOLEAN NOT NULL DEFAULT FALSE,
                balance BIGINT NOT NULL DEFAULT 0 CHECK (balance >= 0),
                last_billing_date DATE
            );
        """

        create_devices = """
            CREATE TABLE IF NOT EXISTS devices (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                device_name TEXT NOT NULL,
                client_uuid TEXT NOT NULL UNIQUE,
                vless_link TEXT,
                monthly_cost INTEGER NOT NULL DEFAULT 10000 CHECK (monthly_cost >= 0),
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            );
        """

        create_payments = """
            CREATE TABLE IF NOT EXISTS payments (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                payload TEXT NOT NULL,
                telegram_charge_id TEXT NOT NULL,
                provider_charge_id TEXT NOT NULL,
                amount INTEGER NOT NULL CHECK (amount >= 0),
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            );
        """

        create_indexes = """
            CREATE UNIQUE INDEX IF NOT EXISTS idx_payments_tg_charge_id
                ON payments(telegram_charge_id);
            CREATE UNIQUE INDEX IF NOT EXISTS idx_payments_provider_charge_id
                ON payments(provider_charge_id);
            CREATE INDEX IF NOT EXISTS idx_payments_user_id ON payments(user_id);
            CREATE INDEX IF NOT EXISTS idx_devices_user_id ON devices(user_id);
            CREATE INDEX IF NOT EXISTS idx_users_uuid ON users(uuid);
        """

        create_active_device_indexes = """
            CREATE INDEX IF NOT EXISTS idx_devices_user_id_is_active
                ON devices(user_id, is_active);
        """

        alter_devices = """
            ALTER TABLE devices
                ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE,
                ADD COLUMN IF NOT EXISTS disabled_at TIMESTAMPTZ,
                ADD COLUMN IF NOT EXISTS disabled_reason TEXT;
        """

        alter_payments = """
            ALTER TABLE payments
                ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'PENDING',
                ADD COLUMN IF NOT EXISTS idempotency_key TEXT;
        """

        alter_users_notifications = """
        ALTER TABLE users
            ADD COLUMN IF NOT EXISTS low_balance_notified BOOLEAN NOT NULL DEFAULT FALSE;
        """

        create_balance_transactions = """
            CREATE TABLE IF NOT EXISTS balance_transactions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                kind TEXT NOT NULL
                    CHECK (kind IN (
                        'TOPUP',
                        'DAILY_CHARGE',
                        'ADMIN_ADJUSTMENT',
                        'REFUND',
                        'BONUS'
                    )),
                amount_cents BIGINT NOT NULL CHECK (amount_cents >= 0),
                balance_before BIGINT NOT NULL CHECK (balance_before >= 0),
                balance_after BIGINT NOT NULL CHECK (balance_after >= 0),
                reference_type TEXT,
                reference_id TEXT,
                idempotency_key TEXT,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            );
        """

        create_balance_indexes = """
            CREATE INDEX IF NOT EXISTS idx_balance_transactions_user_id
                ON balance_transactions(user_id);

            CREATE INDEX IF NOT EXISTS idx_balance_transactions_user_created_at
                ON balance_transactions(user_id, created_at DESC);

            CREATE UNIQUE INDEX IF NOT EXISTS idx_balance_transactions_idempotency_key
                ON balance_transactions(idempotency_key)
                WHERE idempotency_key IS NOT NULL;

            CREATE UNIQUE INDEX IF NOT EXISTS idx_payments_idempotency_key
                ON payments(idempotency_key)
                WHERE idempotency_key IS NOT NULL;
        """

        async with self.transaction() as conn:
            await conn.execute(create_users)
            await conn.execute(create_devices)
            await conn.execute(create_payments)
            await conn.execute(alter_devices)           # ← сначала добавляем колонки
            await conn.execute(alter_payments)
            await conn.execute(alter_users_notifications)
            await conn.execute(create_balance_transactions)
            await conn.execute(create_indexes)          # ← потом индексы
            await conn.execute(create_active_device_indexes)  # ← теперь is_active уже есть
            await conn.execute(create_balance_indexes)      

    @staticmethod
    def _cents_to_rubles(cents: int) -> Decimal:
        return Decimal(cents) / 100

    async def set_user_balance(self, user_id: int, amount_cents: int) -> bool:
        if amount_cents < 0:
            raise ValueError("amount_cents must be >= 0")

        async with self.transaction() as conn:
            row = await conn.fetchrow(
                "SELECT balance FROM users WHERE user_id = $1 FOR UPDATE",
                user_id,
            )
            if not row:
                return False

            balance_before = row["balance"]
            balance_after = amount_cents

            await conn.execute(
                "UPDATE users SET balance = $1 WHERE user_id = $2",
                balance_after,
                user_id,
            )

            await self._create_balance_transaction(
                conn=conn,
                user_id=user_id,
                kind="ADMIN_ADJUSTMENT",
                amount_cents=abs(balance_after - balance_before),
                balance_before=balance_before,
                balance_after=balance_after,
                reference_type="admin_set_balance",
                reference_id=None,
                idempotency_key=None,
            )

            return True


    async def add_balance_atomic(
        self,
        user_id: int,
        amount_cents: int,
        reference_type: Optional[str] = "payment",
        reference_id: Optional[str] = None,
        idempotency_key: Optional[str] = None,
    ) -> Optional[Decimal]:
        if amount_cents < 0:
            raise ValueError("amount_cents must be >= 0")

        async with self.transaction() as conn:
            row = await conn.fetchrow(
                "SELECT balance FROM users WHERE user_id = $1 FOR UPDATE",
                user_id,
            )
            if not row:
                return None

            balance_before = row["balance"]

            updated = await conn.fetchrow(
                """
                UPDATE users
                SET balance = balance + $1
                WHERE user_id = $2
                RETURNING balance
                """,
                amount_cents,
                user_id,
            )
            balance_after = updated["balance"]

            await self._create_balance_transaction(
                conn=conn,
                user_id=user_id,
                kind="TOPUP",
                amount_cents=amount_cents,
                balance_before=balance_before,
                balance_after=balance_after,
                reference_type=reference_type,
                reference_id=reference_id,
                idempotency_key=idempotency_key,
            )

            return self._cents_to_rubles(balance_after)

    async def _create_balance_transaction(
        self,
        conn: asyncpg.Connection,
        user_id: int,
        kind: str,
        amount_cents: int,
        balance_before: int,
        balance_after: int,
        reference_type: Optional[str] = None,
        reference_id: Optional[str] = None,
        idempotency_key: Optional[str] = None,
    ) -> int:
        row = await conn.fetchrow(
            """
            INSERT INTO balance_transactions (
                user_id,
                kind,
                amount_cents,
                balance_before,
                balance_after,
                reference_type,
                reference_id,
                idempotency_key
            )
            VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
            RETURNING id
            """,
            user_id,
            kind,
            amount_cents,
            balance_before,
            balance_after,
            reference_type,
            reference_id,
            idempotency_key,
        )
        return row["id"]

    async def charge_balance_atomic(
        self,
        user_id: int,
        amount_cents: int,
        reference_type: Optional[str] = "manual_charge",
        reference_id: Optional[str] = None,
        idempotency_key: Optional[str] = None,
    ) -> Optional[Dict[str, Any]]:
        if amount_cents < 0:
            raise ValueError("amount_cents must be >= 0")

        async with self.transaction() as conn:
            row = await conn.fetchrow(
                "SELECT balance FROM users WHERE user_id = $1 FOR UPDATE",
                user_id,
            )
            if not row:
                return None

            balance_before = row["balance"]
            if balance_before < amount_cents:
                return {
                    "charged": False,
                    "insufficient_funds": True,
                    "balance_before": self._cents_to_rubles(balance_before),
                    "balance_after": self._cents_to_rubles(balance_before),
                }

            updated = await conn.fetchrow(
                """
                UPDATE users
                SET balance = balance - $1
                WHERE user_id = $2 AND balance >= $1
                RETURNING balance
                """,
                amount_cents,
                user_id,
            )
            if not updated:
                return {
                    "charged": False,
                    "insufficient_funds": True,
                    "balance_before": self._cents_to_rubles(balance_before),
                    "balance_after": self._cents_to_rubles(balance_before),
                }

            balance_after = updated["balance"]

            await self._create_balance_transaction(
                conn=conn,
                user_id=user_id,
                kind="ADMIN_ADJUSTMENT",
                amount_cents=amount_cents,
                balance_before=balance_before,
                balance_after=balance_after,
                reference_type=reference_type,
                reference_id=reference_id,
                idempotency_key=idempotency_key,
            )

            return {
                "charged": True,
                "insufficient_funds": False,
                "balance_before": self._cents_to_rubles(balance_before),
                "balance_after": self._cents_to_rubles(balance_after),
            }

    async def charge_daily_billing_atomic(
        self,
        user_id: int,
        amount_cents: int,
        billing_date: date,
    ) -> Optional[Dict[str, Any]]:
        if amount_cents < 0:
            raise ValueError("amount_cents must be >= 0")

        async with self.transaction() as conn:
            row = await conn.fetchrow(
                "SELECT balance, last_billing_date FROM users WHERE user_id = $1 FOR UPDATE",
                user_id,
            )
            if not row:
                return None

            balance_before = row["balance"]
            last_bill = row["last_billing_date"]

            if last_bill is not None and last_bill == billing_date:
                return {
                    "charged": False,
                    "already_charged_today": True,
                    "insufficient_funds": False,
                    "balance_before": self._cents_to_rubles(balance_before),
                    "balance_after": self._cents_to_rubles(balance_before),
                }

            if balance_before < amount_cents:
                return {
                    "charged": False,
                    "already_charged_today": False,
                    "insufficient_funds": True,
                    "balance_before": self._cents_to_rubles(balance_before),
                    "balance_after": self._cents_to_rubles(balance_before),
                }

            updated = await conn.fetchrow(
                """
                UPDATE users
                SET balance = balance - $1, last_billing_date = $2
                WHERE user_id = $3 AND balance >= $1
                RETURNING balance
                """,
                amount_cents,
                billing_date,
                user_id,
            )
            if not updated:
                return {
                    "charged": False,
                    "already_charged_today": False,
                    "insufficient_funds": True,
                    "balance_before": self._cents_to_rubles(balance_before),
                    "balance_after": self._cents_to_rubles(balance_before),
                }

            balance_after = updated["balance"]

            await self._create_balance_transaction(
                conn=conn,
                user_id=user_id,
                kind="DAILY_CHARGE",
                amount_cents=amount_cents,
                balance_before=balance_before,
                balance_after=balance_after,
                reference_type="billing",
                reference_id=str(billing_date),
                idempotency_key=f"daily:{user_id}:{billing_date.isoformat()}",
            )

            return {
                "charged": True,
                "already_charged_today": False,
                "insufficient_funds": False,
                "balance_before": self._cents_to_rubles(balance_before),
                "balance_after": self._cents_to_rubles(balance_after),
            }

    async def save_user(
        self,
        user_id: int,
        username: str,
        expire_at: Optional[datetime],
        vless_link: Optional[str],
        uuid_val: Optional[str],
        status: str = "TRIAL",
    ) -> None:
        async with self.transaction() as conn:
            await conn.execute(
                """
                INSERT INTO users (
                    user_id, username, expire_at, vless_link, uuid, status, notified, low_balance_notified
                )
                VALUES ($1, $2, $3, $4, $5, $6, FALSE, FALSE)
                ON CONFLICT (user_id) DO UPDATE SET
                    username = EXCLUDED.username,
                    expire_at = EXCLUDED.expire_at,
                    vless_link = EXCLUDED.vless_link,
                    uuid = EXCLUDED.uuid,
                    status = EXCLUDED.status,
                    notified = FALSE,
                    low_balance_notified = FALSE
                """,
                user_id, username, expire_at, vless_link, uuid_val, status,
            )

